#!/usr/bin/env bash
#
# Writes one tiny manifest per MCU: <outdir>/ports-<cpu_name>.dmm.
#
# The main manifest.dmm has a single
#     $include .../ports-<cpu_name>.dmm
# and so a chip gets exactly one dmcrypto_port - the hardware port of its
# family or the software port - under the one name dmf-get resolves
# dependencies by. Which one is src/port/*/mcus.txt (see there): each line is
#     <cpu_name> hw|sw
# (<cpu_name> is dmod-boot's DMOD_CPU_NAME, lower case, e.g. stm32f746xg).
#
# Usage: scripts/gen-ports-manifests.sh OUTDIR
set -euo pipefail

root=$(cd "$(dirname "$0")/.." && pwd)
out=${1:?usage: $0 OUTDIR}
base=https://github.com/choco-technologies/dmcrypto/releases/download
mkdir -p "$out"

count=0
declare -A seen
for list in "$root"/src/port/*/mcus.txt; do
    family=$(basename "$(dirname "$list")")
    while read -r cpu kind rest; do
        case "$cpu" in ''|'#'*) continue ;; esac
        if [ -n "$rest" ] || { [ "$kind" != hw ] && [ "$kind" != sw ]; }; then
            echo "$list: '$cpu $kind $rest': expected '<cpu_name> hw|sw'" >&2
            exit 1
        fi
        if [[ ! "$cpu" =~ ^[a-z0-9_]+$ ]]; then
            echo "$list: cpu_name '$cpu' must be lower case letters, digits, '_'" >&2
            exit 1
        fi
        if [ -n "${seen[$cpu]:-}" ]; then
            echo "$list: '$cpu' is already in ${seen[$cpu]}" >&2
            exit 1
        fi
        if [ "$kind" = hw ] && [ "$family" = sw ]; then
            echo "$list: '$cpu': the software list cannot have a hardware port" >&2
            exit 1
        fi
        seen[$cpu]=$list
        if [ "$kind" = hw ]; then
            url="$base/v<version>/dmcrypto_port-v<version>-<cpu_family>.zip"
            what="the hardware port of its CPU family"
        else
            url="$base/v<version>/dmcrypto_port_sw-v<version>-<arch_name>.zip"
            what="the software port (it has no hardware this port uses)"
        fi
        cat > "$out/ports-$cpu.dmm" <<DMM
# dmcrypto_port for $cpu: $what.
# Generated by scripts/gen-ports-manifests.sh from $(basename "$(dirname "$list")")/mcus.txt.
# The versions are versions.dmm's (\$version-available dmcrypto_port).
dmcrypto_port $url
DMM
        count=$((count + 1))
    done < "$list"
done
echo "$count MCU manifest(s) in $out"
